function mergeWebProvider(localeCode) {
  const filePath = path.join(localesDir, `${localeCode}.json`);
  const raw = JSON.parse(fs.readFileSync(filePath, "utf8"));
  raw.web = raw.web ?? {};
  raw.web.provider = webProvider;
  fs.writeFileSync(filePath, `${JSON.stringify(raw, null, 2)}\n`);
  console.log(`Updated ${localeCode}.json`);
}

for (const code of ["en", "fr", "ar", "sw"]) {
  mergeWebProvider(code);
}
