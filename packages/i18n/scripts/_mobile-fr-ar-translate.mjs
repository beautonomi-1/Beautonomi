function protectTokens(str) {
  const tokens = [];
  let out = str.replace(/\{\{(\w+)\}\}/g, (_, name) => {
    const i = tokens.length;
    tokens.push(`{{${name}}}`);
    return `\u0000${i}\u0000`;
  });
  for (const brand of BRANDS) {
    const re = new RegExp(brand.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"), "g");
    out = out.replace(re, () => {
      const i = tokens.length;
      tokens.push(brand);
      return `\u0000${i}\u0000`;
    });
  }
  return { out, tokens };
}

function restoreTokens(str, tokens) {
  return str.replace(/\u0000(\d+)\u0000/g, (_, i) => tokens[Number(i)] ?? "");
}

function preserveCase(src, dest) {
  if (src === src.toUpperCase() && src.length > 1) return dest.toUpperCase();
  if (src[0] === src[0]?.toUpperCase()) {
    return dest.charAt(0).toUpperCase() + dest.slice(1);
  }
  return dest;
}

function applyLongest(str, table, localeIdx) {
  let out = str;
  for (const row of table) {
    const en = row[0];
    const tr = row[localeIdx];
    if (!en || !tr) continue;
    const escaped = en.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const starts = /^\w/.test(en);
    const ends = /\w$/.test(en);
    const re = new RegExp(`${starts ? "\\b" : ""}${escaped}${ends ? "\\b" : ""}`, "gi");
    out = out.replace(re, (match) => preserveCase(match, tr));
  }
  return out;
}

function wordCount(s) {
  return (String(s).match(/[A-Za-z\u00C0-\u024F']+/g) || []).length;
}

export function translateMobile(en, locale) {
  if (typeof en !== "string" || isIdentity(en)) return en;
  const exact = MOBILE_EXACT.get(en);
  if (exact?.[locale]) return exact[locale];

  const idx = locale === "fr" ? 1 : 2;
  const { out: protectedStr, tokens } = protectTokens(en);
  let out = applyLongest(protectedStr, PHRASES, idx);
  if (wordCount(en) <= 12) {
    out = applyLongest(out, WORDS, idx);
  }
  out = restoreTokens(out, tokens);
  return out;
}

export function mobilePair(en) {
  if (isIdentity(en)) return null;
  const fr = translateMobile(en, "fr");
  const ar = translateMobile(en, "ar");
  if (fr === en && ar === en) return null;
  return { fr, ar };
}
