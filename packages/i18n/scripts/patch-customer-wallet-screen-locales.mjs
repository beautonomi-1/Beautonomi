function deepSet(obj, dotted, value) {
  const parts = dotted.split(".");
  let cur = obj;
  for (let i = 0; i < parts.length - 1; i++) {
    const p = parts[i];
    if (!cur[p] || typeof cur[p] !== "object") cur[p] = {};
    cur = cur[p];
  }
  cur[parts[parts.length - 1]] = value;
}

for (const locale of TARGET_LOCALES) {
  const pack = WALLET[locale];
  if (!pack) {
    console.warn(`skip ${locale}: no wallet pack`);
    continue;
  }
  const localePath = path.join(LOCALES_DIR, `${locale}.json`);
  const data = JSON.parse(fs.readFileSync(localePath, "utf8"));
  for (const [suffix, val] of Object.entries(pack)) {
    deepSet(data, `customer.walletScreen.${suffix}`, val);
  }
  safeWriteJson(localePath, data);
  console.log(`${locale}: wallet ${Object.keys(pack).length} keys`);
}
