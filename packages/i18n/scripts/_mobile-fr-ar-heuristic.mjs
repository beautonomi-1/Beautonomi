function applyFrags(str, table) {
  let out = str;
  for (const [from, to] of table) {
    if (out.includes(from)) out = out.split(from).join(to);
  }
  return out;
}

export function heuristicMobile(en, locale) {
  if (typeof en !== "string") return en;
  const table = locale === "fr" ? FR_FRAG : AR_FRAG;
  let out = applyFrags(en, table);
  if (locale === "fr") {
    out = out
      .replace(/\bmin\b/g, "min")
      .replace(/\bago\b/g, "")
      .replace(/\bcharacters\b/gi, "caractères")
      .replace(/\brecipient(s)?\b/gi, (_, s) => (s ? "destinataires" : "destinataire"))
      .replace(/\bconversation(s)?\b/gi, (_, s) => (s ? "conversations" : "conversation"))
      .replace(/\bsold\b/gi, "vendus")
      .replace(/\bunread\b/gi, "non lus");
  }
  return out;
}
