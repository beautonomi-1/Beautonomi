/**
 * Regenerates apps/web/src/lib/iap/apple/apple-root-ca.ts from the published
 * Apple Root CA - G3 certificate.
 *
 * Usage: node scripts/generate-apple-root-ca.mjs [path-to-AppleRootCA-G3.cer]
 * Default source: https://www.apple.com/certificateauthority/AppleRootCA-G3.cer
 */

import { createHash, X509Certificate } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const SOURCE_URL = "https://www.apple.com/certificateauthority/AppleRootCA-G3.cer";
const OUT_PATH = "apps/web/src/lib/iap/apple/apple-root-ca.ts";

const localPath = process.argv[2];
let der;
if (localPath) {
  der = readFileSync(localPath);
} else {
  const res = await fetch(SOURCE_URL);
  if (!res.ok) throw new Error(`Failed to download root CA: ${res.status}`);
  der = Buffer.from(await res.arrayBuffer());
}

const cert = new X509Certificate(der);
const subject = cert.subject.replace(/\r?\n/g, ", ");
if (!subject.includes("Apple Root CA - G3")) {
  throw new Error(`Unexpected certificate subject: ${subject}`);
}

const base64 = der.toString("base64");
const fingerprint = createHash("sha256")
  .update(der)
  .digest("hex")
  .toUpperCase()
  .match(/../g)
  .join(":");

const pemLines = base64.match(/.{1,64}/g);

const file = `/**
 * Apple Root CA - G3, the trust anchor for App Store Server JWS signatures.
 *
 * Source: ${SOURCE_URL}
 * Subject: ${subject}
 * SHA-256: ${fingerprint}
 * Valid:   ${cert.validFrom} -> ${cert.validTo}
 *
 * Generated by scripts/generate-apple-root-ca.mjs. Do not hand-edit.
 */

export const APPLE_ROOT_CA_G3_SHA256 = "${fingerprint}";

export const APPLE_ROOT_CA_G3_BASE64 = "${base64}";

export const APPLE_ROOT_CA_G3_PEM = [
  "-----BEGIN CERTIFICATE-----",
${pemLines.map((line) => `  "${line}",`).join("\n")}
  "-----END CERTIFICATE-----",
  "",
].join("\\n");
`;

writeFileSync(OUT_PATH, file);
console.log(`Wrote ${OUT_PATH}`);
console.log(`Subject: ${subject}`);
console.log(`SHA-256: ${fingerprint}`);
